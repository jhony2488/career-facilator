function buildRegistry(): JobSource[] {
  const map = new Map<string, JobSource>();
  for (const [category, ids] of Object.entries(GROUPS)) {
    for (const id of ids) {
      const detail = DETAILS[id] ?? {};
      const src = entryFromId(id, detail.category ?? category, detail);
      if (!map.has(src.id)) map.set(src.id, src);
    }
  }
  // Big-tech career pages (html/ats hybrid)
  const bigTech = [
    'microsoftcareers',
    'googlecareers',
    'amazonjobs',
    'applecareers',
    'facebookcareers',
    'teslacareers',
    'salesforcecareers',
    'nvidiacareers',
    'ibmcareers',
    'oraclecareers',
    'gitlabcareers',
    'sapcareers',
    'stripecareers',
    'databrickscareers',
    'openaicareers',
    'palantircareers',
  ];
  for (const id of bigTech) {
    const detail = DETAILS[id] ?? { category: 'ats' };
    const src = entryFromId(id, detail.category ?? 'ats', { ...detail, adapter: 'ats' });
    if (!map.has(src.id)) map.set(src.id, src);
  }
  return Array.from(map.values());
}

export const JOB_SOURCES: JobSource[] = buildRegistry();

export function sourceById(id: string): JobSource | undefined {
  return JOB_SOURCES.find((s) => s.id === id);
}
