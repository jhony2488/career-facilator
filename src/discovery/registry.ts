function titleFromId(id: string): string {
  if (CUSTOM_NAMES[id]) return CUSTOM_NAMES[id];
  return id
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

