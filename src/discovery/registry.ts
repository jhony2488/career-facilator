function entryFromId(id: string, category: string, overrides: Partial<JobSource> = {}): JobSource {
  return {
    id,
    name: overrides.name ?? titleFromId(id),
    category,
    regions: categoryRegions[category],
    adapter: overrides.adapter ?? categoryAdapter[category],
    enabled: false,
    risky: false,
    requiresAuth: false,
    robotsPolicy: 'allow',
    minDelayMs: DEFAULT_DELAY[category],
    workModels: categoryWorkModels[category],
    ...overrides,
  };
}

